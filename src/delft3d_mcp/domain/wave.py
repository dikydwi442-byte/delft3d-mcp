"""Parser and writer for Delft3D-WAVE (.mdw) configuration files."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from delft3d_mcp.domain.mdf import dump_ini_blocks, parse_ini_blocks


def read_mdw(path: Path) -> dict[str, dict[str, str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    return parse_ini_blocks(text)


def write_mdw(path: Path, sections: dict[str, dict[str, Any]]) -> str:
    normalized = {
        sec: {k: str(v) for k, v in kv.items()}
        for sec, kv in sections.items()
    }
    return dump_ini_blocks(normalized, header_comment="Delft3D-WAVE MDW generated by delft3d-mcp")
